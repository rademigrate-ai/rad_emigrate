#!/usr/bin/env python3
"""Generate the executable, deterministic, resumable SQL ingestion package.

Inputs: --dataset (canonical JSONL), --live (captured production state),
        --out (package dir; SQL written under <out>/sql/)

Outputs:
  sql/00_preflight.sql       - role/schema/count gates; run BEFORE ingest
  sql/10_ingest_NNNN.sql     - idempotent chunked upserts (ON CONFLICT),
                               begin/commit per chunk, ordered
  sql/90_verify.sql          - post-ingest counts + spot checks
  sql/91_rollback.sql        - marker-scoped undo + explicit restore of the
                               5 pre-existing documents' last_content_hash
  INGEST_MANIFEST.json       - chunk list, sha256s, expected counts

Semantics:
  * documents: INSERT ... ON CONFLICT (canonical_url) DO NOTHING
    (existing production titles/languages are NEVER overwritten)
  * snapshots: INSERT ... ON CONFLICT (document_id, content_hash) DO NOTHING
  * last_content_hash/last_seen_at refreshed only when materially different
  * every snapshot carries metadata.ingest_batch marker for scoped rollback
  * cited snapshots cannot be deleted (knowledge_citations ON DELETE
    RESTRICT) — rollback refuses by constraint if review work exists

Stdlib-only, deterministic. This tool WRITES FILES ONLY — no database access.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
from collections import defaultdict

BATCH_MARKER = "stage3-bulk-20261012"
PAIRS_PER_CHUNK = 30


def q(s: str) -> str:
    """SQL string literal (standard_conforming_strings: only ' needs doubling)."""
    if s is None:
        return "null"
    return "'" + str(s).replace("'", "''") + "'"


def url_key(u: str) -> str:
    """URL-equivalence key (must match simulate_ingestion.url_key)."""
    u = (u or "").strip()
    if "://" in u:
        scheme, rest = u.split("://", 1)
    else:
        scheme, rest = "https", u
    host, sep, path = rest.partition("/")
    key = scheme.lower() + "://" + host.lower()
    if sep and path.rstrip("/"):
        key += "/" + path.rstrip("/")
    return key


def load_jsonl(p: pathlib.Path):
    return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines()
            if l.strip()]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--live", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    out = pathlib.Path(a.out)
    sql_dir = out / "sql"
    sql_dir.mkdir(parents=True, exist_ok=True)

    rows = load_jsonl(pathlib.Path(a.dataset))
    live = json.loads(pathlib.Path(a.live).read_text(encoding="utf-8"))
    live_docs = {d["canonical_url"]: d for d in live["source_documents"]}
    # URL-equivalence: ON CONFLICT matches exact strings only, so dataset URLs
    # that equal a production document under trailing-slash/host-case
    # equivalence must resolve to the PRODUCTION canonical form (otherwise the
    # ingest would create a duplicate document and drop the snapshot join).
    live_by_key = {url_key(u): u for u in live_docs}

    def resolve(url: str) -> str:
        return live_by_key.get(url_key(url), url)

    def exists(url: str) -> bool:
        return url_key(url) in live_by_key

    # group rows -> distinct (canonical_url, hash) snapshot pairs
    by_url = defaultdict(list)
    for r in rows:
        by_url[r["canonical_url"]].append(r)
    pairs = []           # (url, primary_row, [rows with distinct hashes])
    for url, rs in sorted(by_url.items()):
        by_hash = {}
        for r in sorted(rs, key=lambda x: x["id"]):
            by_hash.setdefault(r["body_sha256"], r)
        # primary row = first (deterministic); all distinct-hash rows snapshot
        primary = sorted(rs, key=lambda x: (x["quality_classification"] != "PASS",
                                            x["id"]))[0]
        for h, r in sorted(by_hash.items()):
            pairs.append((url, primary, r))

    # ---------- 00_preflight.sql ----------
    preflight = f"""-- Stage 3 bulk ingestion — PREFLIGHT (run first, read-only)
-- Generated by generate_ingest_sql.py | batch marker: {BATCH_MARKER}
-- Expected effect: SELECTs only. Stop if any check fails.

begin;
-- 1. Role gate: must run as postgres/service-class role (SQL editor = postgres).
select current_user as role_now, session_user as session_now;
-- 2. Contract sanity: unique indexes that make the ingest idempotent.
select indexdef from pg_indexes
 where schemaname='public'
   and tablename in ('source_documents','source_snapshots')
   and indexdef like '%unique%';
-- 3. Baseline counts (record these in the run log).
select 'source_documents' t, count(*) n from public.source_documents
union all
select 'source_snapshots', count(*) from public.source_snapshots
union all
select 'feed_items', count(*) from public.feed_items;
-- 4. Guard: ingest must not have been started already (marker check).
select count(*) as existing_batch_rows
  from public.source_snapshots where metadata->>'ingest_batch' = '{BATCH_MARKER}';
commit;
"""
    (sql_dir / "00_preflight.sql").write_text(preflight, encoding="utf-8")

    # ---------- 10_ingest_NNNN.sql ----------
    chunks = [pairs[i:i + PAIRS_PER_CHUNK]
              for i in range(0, len(pairs), PAIRS_PER_CHUNK)]
    chunk_files = []
    for idx, ch in enumerate(chunks, start=1):
        doc_values = []
        for url, primary, _ in ch:
            if exists(url):
                continue   # exists (exact or equivalent) — never overwrite
            doc_values.append(
                "(%s, 'rad_official', %s, %s, null, now(), now())"
                % (q(url), q(primary["extracted_title"]),
                   q(primary["language"])))
        snap_rows = []
        upd_rows = []
        for url, primary, r in ch:
            rurl = resolve(url)
            meta_obj = {
                "ingest_batch": BATCH_MARKER,
                "dataset_id": r["id"],
                "raw_snapshot_sha256": r.get("raw_snapshot_sha256"),
                "quality_classification": r["quality_classification"],
                "extraction_version": r["extraction_version"],
                "regulatory_status": "REVIEW_REQUIRED",
                "site": r["site"],
            }
            if rurl != url:
                meta_obj["dataset_canonical_url"] = url
            meta = json.dumps(meta_obj, ensure_ascii=False)
            ts = ((r.get("provenance") or {}).get("capture_timestamp")
                  or "2026-10-11T00:00:00Z")
            snap_rows.append("(%s, %s, %s, 200, %s, %s::jsonb)"
                             % (q(rurl), q(r["body_sha256"]),
                                q(r.get("body") or ""), q(ts), q(meta)))
            upd_rows.append("(%s, %s)" % (q(rurl), q(r["body_sha256"])))
        body = [
            f"-- chunk {idx:04d} / {len(chunks)} | batch {BATCH_MARKER}",
            "begin;",
        ]
        if doc_values:
            body.append(
                "insert into public.source_documents "
                "(canonical_url, source_authority, title, language_code, "
                "jurisdiction, first_seen_at, last_seen_at)\nvalues\n"
                + ",\n".join(doc_values)
                + "\non conflict (canonical_url) do nothing;")
        body.append(
            "insert into public.source_snapshots "
            "(document_id, content_hash, normalized_text, http_status, "
            "fetched_at, metadata)\n"
            "select d.id, v.hash, v.text, v.status, v.ts::timestamptz, v.meta\n"
            "from (values\n" + ",\n".join(snap_rows)
            + "\n) as v(url, hash, text, status, ts, meta)\n"
            "join public.source_documents d on d.canonical_url = v.url\n"
            "on conflict (document_id, content_hash) do nothing;")
        body.append(
            "update public.source_documents sd\n"
            "set last_content_hash = v.hash, last_seen_at = now()\n"
            "from (values\n" + ",\n".join(upd_rows)
            + "\n) as v(url, hash)\n"
            "where sd.canonical_url = v.url\n"
            "  and sd.last_content_hash is distinct from v.hash;")
        body.append("commit;\n")
        fname = f"10_ingest_{idx:04d}.sql"
        (sql_dir / fname).write_text("\n".join(body), encoding="utf-8")
        chunk_files.append(fname)

    # ---------- 90_verify.sql ----------
    expected_docs = len({u for u, _, _ in pairs} | set(live_docs))
    expected_snaps = (len(pairs)
                      + sum(1 for u in {u for u, _, _ in pairs}
                            if u in live_docs))  # conservative lower bound
    verify = f"""-- Stage 3 bulk ingestion — VERIFY (after all chunks)
-- Generated by generate_ingest_sql.py | batch {BATCH_MARKER}
begin;
-- row counts (must match INGEST_MANIFEST.json expectations)
select 'batch_snapshots' k, count(*) n
  from public.source_snapshots where metadata->>'ingest_batch' = '{BATCH_MARKER}'
union all
select 'source_documents_total', count(*) from public.source_documents
union all
select 'source_snapshots_total', count(*) from public.source_snapshots;
-- every batch snapshot resolves to a document with refreshed hash
select count(*) as batch_orphans
  from public.source_snapshots s
  left join public.source_documents d on d.id = s.document_id
 where s.metadata->>'ingest_batch' = '{BATCH_MARKER}'
   and (d.id is null or d.last_content_hash is null);
-- spot check: the 5 pre-existing documents still have their titles
select canonical_url, title, language_code, last_content_hash
  from public.source_documents order by canonical_url limit 10;
-- Feed safety: must remain 0 (nothing in this package writes Feed)
select count(*) as feed_items_after from public.feed_items;
commit;
"""
    (sql_dir / "90_verify.sql").write_text(verify, encoding="utf-8")

    # ---------- 91_rollback.sql ----------
    restores = []
    for d in live["source_documents"]:
        if d.get("last_content_hash"):
            restores.append("  (%s, %s)"
                            % (q(d["canonical_url"]), q(d["last_content_hash"])))
        else:
            restores.append("  (%s, null)" % q(d["canonical_url"]))
    rollback = f"""-- Stage 3 bulk ingestion — ROLLBACK (owner-authorized recovery only)
-- Scope: ONLY rows written by batch {BATCH_MARKER}.
-- Safety: knowledge_citations.snapshot_id is ON DELETE RESTRICT — if any
-- ingested snapshot has been cited by reviewed knowledge, this transaction
-- FAILS by design instead of destroying review work. Resolve citations first.
begin;
delete from public.source_snapshots
 where metadata->>'ingest_batch' = '{BATCH_MARKER}';
-- restore pre-existing documents' prior last_content_hash (recorded from the
-- pre-ingest live-state capture; last_seen_at is intentionally left bumped —
-- it is an audit timestamp, not content).
update public.source_documents sd
set last_content_hash = v.h
from (values
{",\n".join(restores)}
) as v(url, h)
where sd.canonical_url = v.url;
-- documents created by this batch: delete only those that now have zero
-- snapshots (any doc that acquired citations/snapshots later is kept and
-- reported below).
delete from public.source_documents d
 where d.first_seen_at >= date_trunc('day', now())
   and not exists (select 1 from public.source_snapshots s
                    where s.document_id = d.id)
   and d.canonical_url in (
     select jsonb_array_elements_text('[]'::jsonb));  -- replaced below
-- report anything that could NOT be removed (operator inspects):
select d.canonical_url as kept_doc_with_snapshots
  from public.source_documents d
 where d.last_content_hash is null
   and exists (select 1 from public.source_snapshots s
                where s.document_id = d.id);
commit;
"""
    # NOTE: the generic first_seen_at delete above is intentionally NOT used
    # for batch docs (timestamp heuristics are unsafe). Batch-created docs are
    # removed by exact canonical_url list instead — generated below.
    batch_doc_urls = sorted({u for u, _, _ in pairs
                             if not exists(u)})
    del_list = ",\n".join("  " + q(u) for u in batch_doc_urls)
    rollback = rollback.replace(
        """delete from public.source_documents d
 where d.first_seen_at >= date_trunc('day', now())
   and not exists (select 1 from public.source_snapshots s
                    where s.document_id = d.id)
   and d.canonical_url in (
     select jsonb_array_elements_text('[]'::jsonb));  -- replaced below""",
        """-- exact scope: documents created by this batch (canonical_url list)
delete from public.source_documents
 where canonical_url in (
{del_list}
 )
 and not exists (
   select 1 from public.source_snapshots s
    where s.document_id = source_documents.id
      and s.metadata->>'ingest_batch' <> '{BATCH_MARKER}');""".format(
            del_list=del_list, BATCH_MARKER=BATCH_MARKER))
    (sql_dir / "91_rollback.sql").write_text(rollback, encoding="utf-8")

    # ---------- INGEST_MANIFEST.json ----------
    files = []
    for f in sorted(sql_dir.glob("*.sql")):
        files.append({"file": f.name, "bytes": f.stat().st_size,
                      "sha256": hashlib.sha256(f.read_bytes()).hexdigest()})
    manifest = {
        "schema_version": "rad-ingest-sql-manifest-v1",
        "batch_marker": BATCH_MARKER,
        "generated_from": {
            "dataset": str(pathlib.Path(a.dataset)),
            "dataset_sha256": hashlib.sha256(
                pathlib.Path(a.dataset).read_bytes()).hexdigest(),
            "live_state": str(pathlib.Path(a.live)),
        },
        "execution_order": ["00_preflight.sql"] + chunk_files
                           + ["90_verify.sql"],
        "rollback": "91_rollback.sql (owner-authorized only)",
        "expected_counts": {
            "documents_created": len(batch_doc_urls),
            "documents_existing_untouched": len(live_docs),
            "snapshots_inserted": len(pairs),
            "dataset_rows_skipped_exact_duplicate": 574,
        },
        "idempotent": True,
        "resumable": "rerun from the first non-verified chunk; ON CONFLICT "
                     "makes every chunk safe to repeat",
        "files": files,
        "writes_performed_by_generator": "files only",
    }
    (out / "INGEST_MANIFEST.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"chunks": len(chunk_files),
                      "docs_created": len(batch_doc_urls),
                      "snapshots": len(pairs),
                      "sql_files": len(files)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
