"""Generate the client validation subset from the approved RAD v1 registry."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAMES = [
    "ai_orchestrator_response", "save_visa_article_draft_request",
    "save_visa_article_draft_response", "list_research_proposals_response",
    "get_research_proposal_response", "review_research_proposal_response",
    "list_cms_articles_response", "get_cms_article_draft_response",
    "list_cms_articles_request", "get_cms_article_draft_request",
    "list_research_proposals_request", "get_research_proposal_request", "review_research_proposal_request",
]


def generate():
    definitions = json.loads((ROOT / "supabase/contracts/rad_v1.json").read_text(encoding="utf8"))["$defs"]
    selected = {}

    def include(name):
        if name in selected:
            return
        selected[name] = definitions[name]

        def refs(value):
            if isinstance(value, dict):
                if "$ref" in value:
                    include(value["$ref"].split("/")[-1])
                for child in value.values():
                    refs(child)
            elif isinstance(value, list):
                for child in value:
                    refs(child)
        refs(definitions[name])

    for name in NAMES:
        include(name)
    source = "// Generated by scripts/generate_dart_contracts.py. Do not hand edit.\n"
    source += "import 'dart:convert';\n\n"
    source += "final Map<String, dynamic> radContractSchemas =\n    (jsonDecode(r'''"
    source += json.dumps(selected, ensure_ascii=True, separators=(",", ":"))
    source += "''') as Map).cast<String, dynamic>();\n"
    (ROOT / "lib/core/supabase/rad_contract_schemas.dart").write_text(source, encoding="utf8")


if __name__ == "__main__":
    generate()
